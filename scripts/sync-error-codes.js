// Regenerates src/lib/api/error-codes.generated.ts from chairo-api's error catalogue.
// Run after the API adds a code: `npm run sync:error-codes`, then `npm test` lists what still needs Arabic.
const fs = require('node:fs');
const path = require('node:path');

const source = path.resolve(__dirname, '../../chairo-api/src/common/errors/error-codes.ts');
const target = path.resolve(__dirname, '../src/lib/api/error-codes.generated.ts');

const codes = [...fs.readFileSync(source, 'utf8').matchAll(/^ {2}([A-Z][A-Z0-9_]+): *\{/gm)].map((m) => m[1]);
if (!codes.length) throw new Error(`No error codes found in ${source}`);

const lines = codes.map((c) => `  '${c}',`).join('\n');
fs.writeFileSync(
  target,
  `// Generated by scripts/sync-error-codes.js. Do not edit.\nexport const API_ERROR_CODES = [\n${lines}\n] as const;\n`,
);
console.log(`Wrote ${codes.length} codes to ${path.relative(process.cwd(), target)}`);
